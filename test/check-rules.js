function hits(text) {
  const t = norm(text);
  return rules
    .filter((r) => {
      if (r.enabled === false) return false;
      const p = String(r.pattern || "").trim();
      if (!p) return false;
      if (r.type === "regex") return new RegExp(p, "i").test(t);
      return t.toLowerCase().includes(p.toLowerCase());
    })
    .map((r) => r.label || r.id);
}

